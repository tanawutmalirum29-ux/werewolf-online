const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const path = require('path');
const src = fs.readFileSync(path.join(__dirname, '..', 'server.js'), 'utf8');
const start = src.indexOf('function diagnosticIncidentIdentity');
const end = src.indexOf('function validDiagnosticShareToken', start);
assert(start >= 0 && end > start, 'incident identity helper block not found');
const block = src.slice(start, end);
const sandbox = { crypto: require('crypto'), DIAGNOSTIC_INCIDENT_INDEX_PREFIX: 'INCIDENT#' };
vm.runInNewContext(`${block}\nthis.api={diagnosticIncidentIdentity,diagnosticIncidentIndexKey};`, sandbox);
const api = sandbox.api;
const base = { traceId:'tr-123', sessionId:'ses-123', roomId:'I3V9J', operationId:'op-1' };
assert.strictEqual(api.diagnosticIncidentIdentity(base), 'operation:op-1', 'operation ID must be the strongest incident identity');
assert.strictEqual(api.diagnosticIncidentIdentity({...base, operationId:'', requestId:'req-1'}), 'request:req-1', 'request ID must be used when operation is absent');
assert.strictEqual(api.diagnosticIncidentIdentity({...base, operationId:'', requestId:'',}), 'trace:tr-123|session:ses-123|room:I3V9J', 'trace/session/room must group one traced attempt');
assert.strictEqual(api.diagnosticIncidentIdentity({roomId:'I3V9J'}), '', 'room ID alone must never group reports');
const a = api.diagnosticIncidentIndexKey('trace:tr-123|session:ses-123|room:I3V9J');
const b = api.diagnosticIncidentIndexKey('trace:tr-123|session:ses-123|room:I3V9J');
assert.strictEqual(a, b, 'incident index key must be deterministic');
assert(/^INCIDENT#[a-f0-9]{40}$/.test(a), 'incident index key must be a non-sensitive hash');
console.log('diagnostic incident share behavior: PASS');
